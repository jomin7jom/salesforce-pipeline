-- 11_opportunity_access.sql : grants for the existing ADF and Power BI roles (no new users, no passwords)
USE ROLE ACCOUNTADMIN;

-- ADF (SFDC_ADF_SVC / SFDC_ADF_ROLE): call the merge and read COPY_HISTORY for the raw table
GRANT USAGE  ON PROCEDURE LEARNING_DB.DEMO.SP_MERGE_SFDC_OPPORTUNITY() TO ROLE SFDC_ADF_ROLE;
GRANT SELECT ON TABLE     LEARNING_DB.DEMO.SFDC_OPPORTUNITY_RAW        TO ROLE SFDC_ADF_ROLE;  -- for COPY_HISTORY

-- Power BI (SFDC_REPORT_SVC / SFDC_REPORT_ROLE): read-only on the reporting table only
GRANT SELECT ON TABLE     LEARNING_DB.DEMO.SFDC_OPPORTUNITY            TO ROLE SFDC_REPORT_ROLE;

SHOW GRANTS TO ROLE SFDC_ADF_ROLE;
SHOW GRANTS TO ROLE SFDC_REPORT_ROLE;
